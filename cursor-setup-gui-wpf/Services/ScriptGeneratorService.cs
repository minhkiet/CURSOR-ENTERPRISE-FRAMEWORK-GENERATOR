        /// <summary>
        /// Generates the text content of a .bat file from selected template blocks.
        /// </summary>
        public string GenerateBat(ScriptTemplate template, string projectRoot, bool usePowerShell = false)
        {
            var sb = new StringBuilder();

            sb.AppendLine("@echo off");
            sb.AppendLine("REM =============================================================");
            sb.AppendLine($"REM  {template.Name}");
            sb.AppendLine($"REM  Generated by VibeCode Enterprise Framework Setup");
            sb.AppendLine($"REM  Project: {projectRoot}");
            sb.AppendLine($"REM  Date: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            sb.AppendLine("REM =============================================================");
            sb.AppendLine();

            foreach (var block in template.Blocks.Where(b => b.IsSelected))
            {
                sb.AppendLine($"REM ── {block.Title} ──────────────────────────────────────");
                if (!string.IsNullOrWhiteSpace(block.Description))
                    sb.AppendLine($"REM  {block.Description}");
                sb.AppendLine();

                foreach (var line in block.Lines.Where(l => l.Required || block.IsSelected))
                {
                    if (!string.IsNullOrWhiteSpace(line.Comment))
                        sb.AppendLine($"REM  {line.Comment}");

                    string workDir = string.IsNullOrWhiteSpace(line.WorkDir)
                        ? projectRoot
                        : Path.Combine(projectRoot, line.WorkDir);

                    if (!string.IsNullOrWhiteSpace(line.Command))
                    {
                        if (!string.IsNullOrWhiteSpace(workDir) && workDir != projectRoot)
                            sb.AppendLine($"cd /d \"{workDir}\"");
                        else
                            sb.AppendLine($"cd /d \"{projectRoot}\"");

                        if (!string.IsNullOrWhiteSpace(line.Args))
                            sb.AppendLine($"{line.Command} {line.Args}");
                        else
                            sb.AppendLine(line.Command);
                    }
                    sb.AppendLine();
                }
            }

            sb.AppendLine("REM =============================================================");
            sb.AppendLine("echo.");
            sb.AppendLine("echo [OK] Setup complete!");
            sb.AppendLine("pause");
            return sb.ToString();
        }

        /// <summary>
        /// Writes the .bat file to the output directory.
        /// </summary>
        public (bool Success, string Path, string Message) SaveBat(
            ScriptTemplate template, string projectRoot, string outputDir, bool usePowerShell = false)
        {
            try
            {
                string content = GenerateBat(template, projectRoot, usePowerShell);
                string fileName = SanitizeFileName(template.FileName);
                string fullPath = Path.Combine(outputDir, fileName);

                // Ensure output dir exists
                if (!Directory.Exists(outputDir))
                    Directory.CreateDirectory(outputDir);

                // Write with BOM for UTF-8 compatibility
                var encoding = new UTF8Encoding(encoderShouldEmitUTF8Identifier: true);
                File.WriteAllText(fullPath, content, encoding);

                return (true, fullPath, $"Saved: {fullPath}");
            }
            catch (Exception ex)
            {
                return (false, "", ex.Message);
            }
        }

        /// <summary>
        /// Saves all selected templates as .bat files in the output directory.
        /// </summary>
        public List<(string TemplateName, bool Success, string Path, string Message)> SaveAllBats(
            IEnumerable<ScriptTemplate> templates, string projectRoot, string outputDir)
        {
            var results = new List<(string, bool, string, string)>();
            foreach (var t in templates.Where(t => t.IsSelected))
            {
                var r = SaveBat(t, projectRoot, outputDir);
                results.Add((t.Name, r.Success, r.Path, r.Message));
            }
            return results;
        }

        static string SanitizeFileName(string name)
        {
            foreach (char c in Path.GetInvalidFileNameChars())
                name = name.Replace(c, '_');
            if (!name.EndsWith(".bat", StringComparison.OrdinalIgnoreCase))
                name += ".bat";
            return name;
        }

